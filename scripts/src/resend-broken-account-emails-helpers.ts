// Pure helpers for the Task #460 replay script. Extracted so a test
// can exercise the portal-classification logic without importing the
// full script (which pulls in `@workspace/db` and Clerk at module
// load).

export function pickStringField(
  meta: Record<string, unknown> | null,
  ...keys: string[]
): string {
  if (!meta) return "";
  for (const k of keys) {
    const v = meta[k];
    if (typeof v === "string" && v.length > 0) return v;
  }
  return "";
}

// Pick the portal we should re-send the buyer to.
//
// IMPORTANT: do NOT infer the portal from the legacy CTA path. The
// broken batch this script targets was generated by code that
// hardcoded `/portal/*` for everyone, including Room30 buyers, so a
// `/portal/*` value in a stored CTA is meaningless for routing. The
// only authoritative source is `metadata.portalKey` (added in this
// task). When that's missing - which it WILL be for every row in the
// Task #460 broken batch - default to `room30`, matching the
// Whop/Stripe funnel which exclusively sells the Room30 AI Influencer
// Masterclass today.
export function inferPortalKey(
  _ctaUrl: string,
  meta: Record<string, unknown> | null,
): "room30" | "main" {
  const declared = pickStringField(meta, "portalKey");
  if (declared === "main" || declared === "room30") return declared;
  return "room30";
}
