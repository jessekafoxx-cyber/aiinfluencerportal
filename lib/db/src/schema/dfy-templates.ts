import {
  pgTable,
  serial,
  text,
  varchar,
  integer,
  bigint,
  boolean,
  timestamp,
  uniqueIndex,
  index,
  primaryKey,
} from "drizzle-orm/pg-core";
import { portalUsersTable } from "./portal";

// Catalog of DFY template tiles shown across the Done For You Pack
// galleries (Ad Swipe File, Canva Ad Templates, Advertorial Swipe
// File, Funnel Templates, Landing Page Swipes, VSL Swipes). One row
// per imported tile. The (category, sourceDisplayId) pair is unique
// so re-running the importer is idempotent.
export const dfyTemplatesTable = pgTable(
  "dfy_templates",
  {
    id: serial("id").primaryKey(),
    // One of: ad_swipe | canva_ad_template | advertorial_swipe |
    // funnel_template | landing_page_swipe
    category: varchar("category", { length: 32 }).notNull(),
    // Sub-tag preserved when collapsing several CSV exports into one
    // category. Currently used by canva_ad_template to keep
    // monthly_drop / free_template / previous_drop separate.
    subCategory: varchar("sub_category", { length: 32 }),
    // The numeric display_id from the source CSV, kept as text so
    // values like "VSL-1" or admin-created entries can coexist.
    sourceDisplayId: varchar("source_display_id", { length: 64 }),
    title: text("title").notNull(),
    // Stored on our own object storage. Always a /api/portal/images/...
    // path (or another path served by the portal). No supabase URLs.
    imageUrl: text("image_url"),
    // For VSL swipes the "image" can actually be an mp4 — when that
    // is the case mediaKind is 'video' so the gallery can render a
    // <video> element instead of <img>.
    mediaKind: varchar("media_kind", { length: 16 }).notNull().default("image"),
    // Poster/thumbnail frame for video templates. Always a
    // /api/portal/images/... path. Generated by the VSL poster worker
    // (first-frame extract via ffmpeg) for any video that doesn't have
    // one. Null for image-kind rows.
    posterUrl: text("poster_url"),
    // VTT-free plain-text transcript for video templates. Generated by
    // the VSL transcript worker (OpenAI Whisper). Surfaced in the
    // preview dialog with a one-click copy button.
    transcript: text("transcript"),
    canvaUrl: text("canva_url"),
    // Live URL of the original asset (used by landing_page_swipe and
    // advertorial_swipe tiles for the "Preview" action so the user
    // opens the real, in-the-wild page rather than just our archived
    // screenshot). Optional; tiles fall back to the local image
    // preview when this is null.
    liveUrl: text("live_url"),
    // Downloadable PDF capture of the asset. Surfaced as the
    // "Download" action on landing_page_swipe and advertorial_swipe
    // tiles. Either a /api/portal/images/... path served from object
    // storage or a fully-qualified https URL.
    pdfUrl: text("pdf_url"),
    industry: text("industry"),
    awarenessStage: text("awareness_stage"),
    ratio: varchar("ratio", { length: 16 }),
    theme: text("theme"),
    // T262: the new Ad Swipe export ships up to three theme tags per
    // row. We keep them as discrete columns so we can show all three in
    // the detail dialog and aggregate them into a single Theme filter.
    theme2: text("theme2"),
    theme3: text("theme3"),
    platform: varchar("platform", { length: 32 }),
    brandName: text("brand_name"),
    // T262: full multi-line ad copy from the source CSV. Surfaced in
    // the detail dialog with a copy-to-clipboard button.
    adCopy: text("ad_copy"),
    // T262: source Drive file's modifiedTime (when the row was
    // imported from a Drive folder). Lets the importer detect upstream
    // edits and re-download only when the file actually changed.
    driveModifiedTime: timestamp("drive_modified_time", {
      withTimezone: true,
    }),
    sortOrder: integer("sort_order").notNull().default(0),
    isActive: boolean("is_active").notNull().default(true),
    createdAt: timestamp("created_at", { withTimezone: true })
      .defaultNow()
      .notNull(),
    updatedAt: timestamp("updated_at", { withTimezone: true })
      .defaultNow()
      .notNull(),
  },
  (t) => ({
    catIdx: index("dfy_templates_category_idx").on(t.category),
    sortIdx: index("dfy_templates_sort_idx").on(t.category, t.sortOrder),
    sourceUq: uniqueIndex("dfy_templates_source_uq").on(
      t.category,
      t.sourceDisplayId,
    ),
  }),
);

export type DfyTemplate = typeof dfyTemplatesTable.$inferSelect;

// Per-user favourites. Composite PK so a user can only favourite a
// given template once.
export const dfyTemplateFavouritesTable = pgTable(
  "dfy_template_favourites",
  {
    userId: integer("user_id")
      .notNull()
      .references(() => portalUsersTable.id, { onDelete: "cascade" }),
    templateId: integer("template_id")
      .notNull()
      .references(() => dfyTemplatesTable.id, { onDelete: "cascade" }),
    createdAt: timestamp("created_at", { withTimezone: true })
      .defaultNow()
      .notNull(),
  },
  (t) => ({
    pk: primaryKey({ columns: [t.userId, t.templateId] }),
    userIdx: index("dfy_template_favourites_user_idx").on(t.userId),
  }),
);

export type DfyTemplateFavourite = typeof dfyTemplateFavouritesTable.$inferSelect;

// T257: Background Reel Music library. Tracks imported from the two
// curated Google Drive folders. drive_file_id is unique so the
// importer is idempotent across runs; drive_modified_time gates
// re-processing of changed source files.
export const dfyBackgroundTracksTable = pgTable(
  "dfy_background_tracks",
  {
    id: serial("id").primaryKey(),
    driveFileId: text("drive_file_id").notNull(),
    driveModifiedTime: timestamp("drive_modified_time", { withTimezone: true }),
    displayTitle: text("display_title").notNull(),
    originalFilename: text("original_filename").notNull(),
    mimeType: varchar("mime_type", { length: 64 }).notNull().default("audio/mpeg"),
    fileSize: bigint("file_size", { mode: "number" }),
    durationSeconds: integer("duration_seconds"),
    bitrateBps: integer("bitrate_bps"),
    originalObjectKey: text("original_object_key").notNull(),
    previewObjectKey: text("preview_object_key"),
    // T396: short, unique, human-readable code (e.g. "BGM-A7K3X2") so a
    // user can search the library and find the same track again later.
    // Generated at insert time; backfilled for legacy rows by migration
    // 0040 and a defensive boot hook in dfy-background-music-importer.
    trackCode: text("track_code").notNull(),
    sortOrder: integer("sort_order").notNull().default(0),
    isActive: boolean("is_active").notNull().default(true),
    createdAt: timestamp("created_at", { withTimezone: true })
      .defaultNow()
      .notNull(),
    updatedAt: timestamp("updated_at", { withTimezone: true })
      .defaultNow()
      .notNull(),
  },
  (t) => ({
    driveUq: uniqueIndex("dfy_background_tracks_drive_uq").on(t.driveFileId),
    activeSortIdx: index("dfy_background_tracks_active_sort_idx").on(
      t.isActive,
      t.sortOrder,
    ),
    trackCodeUq: uniqueIndex("dfy_background_tracks_code_uq").on(t.trackCode),
  }),
);

export type DfyBackgroundTrack = typeof dfyBackgroundTracksTable.$inferSelect;
