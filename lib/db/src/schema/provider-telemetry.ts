import {
  pgTable,
  serial,
  text,
  integer,
  boolean,
  timestamp,
  jsonb,
  real,
  index,
  uniqueIndex,
} from "drizzle-orm/pg-core";

// ─────────────────────────────────────────────────────────────────────────────
// Slice D - Provider Reliability Telemetry + Observability.
//
// Three tables, all append-only or write-once-rolled-up. None of these
// rows feed orchestration decisions in this slice; they exist purely
// for forensic visibility, historical analytics, and as the data
// foundation that future routing/failover/scoring slices will read
// from.
// ─────────────────────────────────────────────────────────────────────────────

// One row per provider call attempt (submit, webhook, poll). Hot
// append-only audit log. Recorder is fire-and-forget and non-throwing
// so a recording failure can never fail a provider request.
export const providerExecutionEventsTable = pgTable(
  "provider_execution_events",
  {
    id: serial("id").primaryKey(),
    // higgsfield / enhancor / gemini
    provider: text("provider").notNull(),
    // submit / webhook / poll / recovery / preflight
    operation: text("operation").notNull(),
    // base_generation / enhancement / scene_swap / base_fallback / null
    stage: text("stage"),
    jobId: integer("job_id"),
    sceneJobId: integer("scene_job_id"),
    providerJobId: text("provider_job_id"),
    success: boolean("success").notNull(),
    // True when the call returned a usable result via the
    // degraded path (e.g. Enhancor empty payload -> base portrait
    // passthrough). Counted separately from outright failure.
    degraded: boolean("degraded").notNull().default(false),
    // Channel flags so rollups can compute webhook-vs-poll mix without
    // recomputing from operation strings.
    webhookUsed: boolean("webhook_used").notNull().default(false),
    pollUsed: boolean("poll_used").notNull().default(false),
    latencyMs: integer("latency_ms"),
    outputBytes: integer("output_bytes"),
    // FailureClass from shared/types.ts (RATE_LIMIT, TIMEOUT, etc).
    errorClass: text("error_class"),
    // Legacy InfluencerErrorCode (PROVIDER_TIMEOUT, EMPTY_OUTPUT, etc).
    errorCode: text("error_code"),
    errorMessage: text("error_message"),
    // Worker process id when emitted from the worker host.
    workerId: text("worker_id"),
    metadata: jsonb("metadata").$type<Record<string, unknown>>().notNull().default({}),
    createdAt: timestamp("created_at", { withTimezone: true }).notNull().defaultNow(),
  },
  (table) => ({
    providerCreatedIdx: index("provider_exec_events_provider_created_idx").on(
      table.provider,
      table.createdAt,
    ),
    jobIdx: index("provider_exec_events_job_idx").on(table.jobId),
    createdIdx: index("provider_exec_events_created_idx").on(table.createdAt),
  }),
);

export type ProviderExecutionEvent = typeof providerExecutionEventsTable.$inferSelect;
export type InsertProviderExecutionEvent = typeof providerExecutionEventsTable.$inferInsert;

// Hourly rollup of execution events. Generated by
// `runProviderHealthRollup()` in the Media Worker. UNIQUE
// (provider, window_start) prevents duplicate rollups under retry or
// concurrent worker instances.
export const providerHealthSnapshotsTable = pgTable(
  "provider_health_snapshots",
  {
    id: serial("id").primaryKey(),
    provider: text("provider").notNull(),
    windowStart: timestamp("window_start", { withTimezone: true }).notNull(),
    windowEnd: timestamp("window_end", { withTimezone: true }).notNull(),
    sampleSize: integer("sample_size").notNull(),
    successRate: real("success_rate").notNull(),
    avgLatencyMs: integer("avg_latency_ms"),
    p50LatencyMs: integer("p50_latency_ms"),
    p95LatencyMs: integer("p95_latency_ms"),
    p99LatencyMs: integer("p99_latency_ms"),
    timeoutRate: real("timeout_rate").notNull(),
    emptyOutputRate: real("empty_output_rate").notNull(),
    webhookFailureRate: real("webhook_failure_rate").notNull(),
    degradedRate: real("degraded_rate").notNull(),
    // Per-error-class counts and per-operation counts inside this
    // window. Stored as JSON so future error classes do not require
    // a column add.
    breakdown: jsonb("breakdown").$type<Record<string, unknown>>().notNull().default({}),
    generatedAt: timestamp("generated_at", { withTimezone: true }).notNull().defaultNow(),
  },
  (table) => ({
    providerWindowIdx: index("provider_health_snapshots_provider_window_idx").on(
      table.provider,
      table.windowStart,
    ),
    providerWindowUq: uniqueIndex("provider_health_snapshots_provider_window_uq").on(
      table.provider,
      table.windowStart,
    ),
  }),
);

export type ProviderHealthSnapshot = typeof providerHealthSnapshotsTable.$inferSelect;
export type InsertProviderHealthSnapshot = typeof providerHealthSnapshotsTable.$inferInsert;

// Structured tap for orchestration recovery actions. Rows here mark
// the moments when the orchestration engine took a recovery path
// (Gemini base fallback, Enhancor degraded passthrough, stuck reclaim,
// HF poll-driven Gemini fallback). Visibility into these is the
// signal "how often do we have to save a job" - critical input for
// any future routing/failover decision.
export const providerRecoveryEventsTable = pgTable(
  "provider_recovery_events",
  {
    id: serial("id").primaryKey(),
    jobId: integer("job_id").notNull(),
    // gemini_base_fallback
    // enhancor_degraded_passthrough
    // hf_poll_to_gemini_fallback
    // stuck_generating_base_reclaim
    // stuck_enhancing_reclaim
    recoveryKind: text("recovery_kind").notNull(),
    fromProvider: text("from_provider"),
    toProvider: text("to_provider"),
    stage: text("stage"),
    reason: text("reason"),
    success: boolean("success").notNull(),
    // Time from the original failure / stuck detection to the recovery
    // action. Helps measure recovery latency.
    delayMs: integer("delay_ms"),
    metadata: jsonb("metadata").$type<Record<string, unknown>>().notNull().default({}),
    createdAt: timestamp("created_at", { withTimezone: true }).notNull().defaultNow(),
  },
  (table) => ({
    kindCreatedIdx: index("provider_recovery_events_kind_created_idx").on(
      table.recoveryKind,
      table.createdAt,
    ),
    jobIdx: index("provider_recovery_events_job_idx").on(table.jobId),
  }),
);

export type ProviderRecoveryEvent = typeof providerRecoveryEventsTable.$inferSelect;
export type InsertProviderRecoveryEvent = typeof providerRecoveryEventsTable.$inferInsert;
